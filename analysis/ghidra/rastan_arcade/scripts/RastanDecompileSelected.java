// Deterministic selected-function decompiler for durable Rastan arcade evidence.
// Usage: -postScript RastanDecompileSelected.java OUTPUT_DIR HEX_PC [HEX_PC ...]
import java.io.File;
import java.io.PrintWriter;

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.listing.Function;

public class RastanDecompileSelected extends GhidraScript {
    @Override
    protected void run() throws Exception {
        String[] args = getScriptArgs();
        if (args.length < 2) {
            throw new IllegalArgumentException("OUTPUT_DIR and at least one HEX_PC are required");
        }
        File outDir = new File(args[0]);
        if (!outDir.isDirectory() && !outDir.mkdirs()) {
            throw new IllegalStateException("cannot create " + outDir);
        }
        DecompInterface decomp = new DecompInterface();
        decomp.toggleCCode(true);
        decomp.toggleSyntaxTree(true);
        if (!decomp.openProgram(currentProgram)) {
            throw new IllegalStateException("decompiler could not open program");
        }
        for (int i = 1; i < args.length; i++) {
            long pc = Long.parseUnsignedLong(args[i].replaceFirst("^(0x|0X)", ""), 16);
            Address address = toAddr(pc);
            Function fn = getFunctionAt(address);
            if (fn == null) {
                disassemble(address);
                fn = createFunction(address, "arcade_" + Long.toHexString(pc));
            }
            if (fn == null) {
                throw new IllegalStateException("no function at " + address);
            }
            DecompileResults result = decomp.decompileFunction(fn, 120, monitor);
            if (!result.decompileCompleted()) {
                throw new IllegalStateException("decompile failed at " + address + ": " + result.getErrorMessage());
            }
            File out = new File(outDir, String.format("%08x.c", pc));
            try (PrintWriter writer = new PrintWriter(out, "UTF-8")) {
                writer.printf("/* ORIGINAL ARCADE PC: 0x%08X */%n", pc);
                writer.println("/* Generated by canonical Ghidra project + RastanDecompileSelected.java. */");
                writer.println(result.getDecompiledFunction().getC());
            }
            println("DECOMPILED " + address + " -> " + out);
        }
        decomp.dispose();
    }
}
