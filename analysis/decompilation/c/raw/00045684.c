/* ORIGINAL ARCADE PC: 0x00045684 palette-attribute resolver (sets actor +0x27 palette line).
 * RECONSTRUCTED_FROM_68000. Status: COMPLETE.
 * Called at actor setup. Computes the PC090OJ palette line (nibble) and ORs it (with bit6) into the
 * actor's +0x27 palette attribute. Two paths by family (+0x3E):
 *
 *  family != 2 (normal field/materialized):
 *      table = 0x45722 (or 0x4576A when A5+0x2A2 != 0);  a0 = table + (round-1)*12 + family(+0x3E)
 *      nibble = a0[0]
 *  family == 2 (the 0x033E hunter and everything it materializes):
 *      table = 0x456EC;  a0 = table + variant(+0x752)*18 + (round-1)*3 + comp_adj
 *          comp_adj: d0 = +0x38; if d0 >= 3 then d0 -= 2;   (comp 0..2 -> 0..2)
 *      nibble = a0[0]
 *  common tail (0x456B0): +0x27 |= (nibble | 0x40).
 *
 * The final 16 colors come from the per-round ROM palette (0x3BA88[round-1][nibble] -> pool ->
 * 0x4FD02), i.e. the same rom_field_palette(round, nibble) the field actors use. The palette line is
 * therefore ROUND-SPECIFIC (per-round table row) and, for family-2, also variant/comp specific. */
#include "raw_common.h"

/* 0x45722: non-family-2 nibble table, (round-1)*12 + family. */
static const uint8_t pal_nib_45722[72] = {
 0x06,0x04,0x07,0x0a,0x07,0x06,0x08,0x0f,0x02,0x01,0x0b,0x0e,
 0x06,0x04,0x07,0x0a,0x07,0x06,0x08,0x0f,0x02,0x01,0x0b,0x0e,
 0x06,0x04,0x07,0x0a,0x07,0x06,0x08,0x0f,0x02,0x01,0x0b,0x0e,
 0x06,0x04,0x07,0x0a,0x07,0x06,0x08,0x0f,0x02,0x01,0x0b,0x0e,
 0x06,0x04,0x07,0x0a,0x07,0x06,0x08,0x02,0x02,0x01,0x0b,0x0e,
 0x06,0x04,0x07,0x0a,0x07,0x06,0x08,0x0f,0x02,0x01,0x0b,0x0e };

/* 0x456EC: family-2 nibble table, variant*18 + (round-1)*3 + comp_adj. */
static const uint8_t pal_nib_456ec[72] = {
 0x04,0x02,0x01,0x04,0x05,0x01,0x00,0x05,0x01,0x00,0x07,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
 0x00,0x00,0x00,0x02,0x00,0x00,0x02,0x00,0x04,0x02,0x05,0x04,0x00,0x05,0x04,0x00,0x00,0x02,
 0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x01,0x00,0x00,0x01,0x07,0x02,0x01,0x07,0x05,
 0x06,0x04,0x07,0x0a,0x07,0x06,0x08,0x0f,0x02,0x01,0x0b,0x0e,0x06,0x04,0x07,0x0a,0x07,0x06 };

extern uint8_t g_round;            /* A5+0x118 */
extern uint16_t g_a5_2a2;          /* A5+0x2A2 (selects 0x4576A alt table when set) */

void arcade_45684(uint8_t *r){
    uint8_t nibble;
    if (B(r,0x3e) != 2){
        /* non-family-2: per-round row (0x4576A alt table not lifted here; same shape) */
        nibble = pal_nib_45722[(g_round-1)*12 + B(r,0x3e)];
    } else {
        uint8_t comp = B(r,0x38);
        uint8_t comp_adj = (comp >= 3) ? (uint8_t)(comp - 2) : comp;
        nibble = pal_nib_456ec[B(r,0x752/*variant*/)*18 + (g_round-1)*3 + comp_adj];
    }
    B(r,0x27) |= (uint8_t)(nibble | 0x40);
}
