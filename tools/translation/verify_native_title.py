#!/usr/bin/env python3
"""Verify the generated one-shot Genesis title presentation artifacts."""

from __future__ import annotations

import argparse
import importlib.util
import json
from pathlib import Path


def load_generator(path: Path):
    spec = importlib.util.spec_from_file_location("gen_native_title", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"cannot import {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--generator", type=Path, required=True)
    ap.add_argument("--maincpu", type=Path, required=True)
    ap.add_argument("--tile-lut", type=Path, required=True)
    ap.add_argument("--attr-lut", type=Path, required=True)
    ap.add_argument("--bg", type=Path, required=True)
    ap.add_argument("--fg", type=Path, required=True)
    ap.add_argument("--fg-invincible", type=Path, required=True)
    ap.add_argument("--palette", type=Path, required=True)
    ap.add_argument("--sat-include", type=Path, required=True)
    ap.add_argument("--report", type=Path, required=True)
    ap.add_argument("--spec", type=Path, required=True)
    ap.add_argument("--title-source", type=Path, required=True)
    args = ap.parse_args()

    gen = load_generator(args.generator)
    result = gen.build(
        args.maincpu.read_bytes(), args.tile_lut.read_bytes(), args.attr_lut.read_bytes()
    )
    expected = {
        args.bg: gen.words_be(result["bg"]),
        args.fg: gen.words_be(result["fg"]),
        args.fg_invincible: gen.words_be(result["fg_invincible"]),
        args.palette: gen.words_be(result["palette"]),
    }
    for path, data in expected.items():
        actual = path.read_bytes()
        if actual != data:
            raise SystemExit(f"native title mismatch: {path}")

    expected_inc = ["/* Generated by gen_native_title.py; {Y, X, glyph}. */"]
    expected_inc += [
        f"    .word 0x{y:04X},0x{x:04X},0x{code:04X}"
        for y, x, code in result["labels"]
    ]
    expected_inc.append("    .word 0xFFFF,0x0000,0x0000")
    if args.sat_include.read_text() != "\n".join(expected_inc) + "\n":
        raise SystemExit("native title SAT include is not generator-exact")

    report = json.loads(args.report.read_text())
    if report.get("semantic_cut") != "arcade 0x03AA54 title presentation entry":
        raise SystemExit("native title report has wrong semantic cut")
    if report.get("dimensions", {}).get("plane_words") != 2048:
        raise SystemExit("native title report has wrong plane dimensions")
    if report.get("static_sat_count") != len(result["labels"]):
        raise SystemExit("native title report has wrong SAT label count")

    remap = json.loads(args.spec.read_text())
    cuts = [
        item
        for item in remap.get("shift_replacements", [])
        if item.get("arcade_pc", "").lower() == "0x03aa54"
    ]
    if len(cuts) != 1 or "genesistan_title_present_once" not in cuts[0].get(
        "replacement_bytes", ""
    ):
        raise SystemExit("missing exact 0x03AA54 native-title shift replacement")

    dispatch_tables = [
        item
        for item in remap.get("jump_table_word_displacements", [])
        if item.get("table_address", "").lower() == "0x03aa20"
    ]
    if len(dispatch_tables) != 1 or dispatch_tables[0].get("entry_count") != 3:
        raise SystemExit("missing exact 0x03AA20 three-entry title dispatch table")

    glyph_cuts = [
        item
        for item in remap.get("shift_replacements", [])
        if item.get("arcade_pc", "").lower() == "0x03bb48"
    ]
    if len(glyph_cuts) != 1:
        raise SystemExit("missing exact 0x03BB48 shift-aware glyph cut")
    glyph_replacement = glyph_cuts[0].get("replacement_bytes", "").upper()
    if "41FA000A" not in glyph_replacement or "GENESISTAN_HOOK_GLYPH_RENDERER_3BD48" not in glyph_replacement:
        raise SystemExit("0x03BB48 glyph cut does not resolve its adjacent table PC-relatively")
    if any(
        item.get("arcade_pc", "").lower() == "0x03bb48"
        for item in remap.get("opcode_replace", [])
    ):
        raise SystemExit("stale byte-neutral 0x03BB48 glyph replacement remains")

    source = args.title_source.read_text()
    required = (
        "genesistan_title_present_once:",
        "genesistan_title_sat_needs_update:",
        "genesistan_title_sat_cache_commit:",
        "native_title_bg_map:",
        "native_title_fg_map:",
    )
    for marker in required:
        if marker not in source:
            raise SystemExit(f"native title source missing {marker}")

    print(
        "NATIVE_TITLE_VERIFY_PASS "
        f"planes=2x{len(result['bg'])} palette={len(result['palette'])} "
        f"static_sat={len(result['labels'])} cut=0x03AA54 dispatch=0x03AA20/3 "
        "glyph_table=pc-relative"
    )


if __name__ == "__main__":
    main()
