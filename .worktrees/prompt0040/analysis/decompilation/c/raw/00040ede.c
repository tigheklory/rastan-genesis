/* ORIGINAL ARCADE PC: 0x00040EDE materialized-actor state 0x20 handler (0x40BAA[0x20]).
 * RECONSTRUCTED_FROM_68000. Status: COMPLETE.
 * State 0x20 is the TORCH / FIRE light-source actor materialized by 0x41BCA ('O'/'P'/'Q').
 *   round==1 & +0x34 in [-384,512): 0x40F52 register light + progress retarget
 *   else recheck +0x0E cell (0x40E74): still present -> animate from 90-frame table 0x40FE0
 *                                      gone       -> 0x40F52 register + retarget chain
 * 0x40F52 writes the light-source record (A5+0x1282 + 6*+0x2F = 0xFF; +0x2F==2 also A5+0x1280),
 * then advances the marker chain by progress band (A5+0x13E), the 0x40F82/0x40FAC/0x40FCC tails:
 *   prog<0x10 : 0x4103A, base=0xDAB, retarget 'I'(0x49), anim 0x74      (0x40F82)
 *   0x10..0x17: 0x4092E step
 *   0x18..0x26: 0x4103A, base=0x9EA, retarget 'a'(0x61)                 (0x40FAC)
 *   0x27..0x4D: 0x4092E step
 *   0x4E..0x53: 0x4103A, base=0x9EA, retarget 'q'(0x71), comp +0x38=2   (0x40FCC)
 *   prog>=0x54: 0x4092E step
 * The 90-byte animation table 0x40FE0 is preserved below (frame index +0x08 -> +0x01).  */
#include "raw_common.h"
