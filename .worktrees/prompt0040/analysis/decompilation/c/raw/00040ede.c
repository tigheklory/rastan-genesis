/* 0x40F52: register light source + progress-band retarget chain. */
static void light_register_40f52(uint8_t *r){
    g_a5_lightrec_1282[3*(uint8_t)B(r,0x2f)] = 0xff;   /* A5+0x1282 + 6*+0x2F (word) = 0xFF */
    if (B(r,0x2f)==2) g_a5_1280 = 0xff;
    uint16_t prog=g_prog13e;
    if (prog<0x10){ arc_4103a(r); W(r,0x1e)=0x0dab; B(r,0x0d)=0x49; B(r,0x01)=0x74; return; }
    if (prog<0x18){ arc_4092e(r); return; }
    if (prog<0x27){ arc_4103a(r); W(r,0x1e)=0x09ea; B(r,0x0d)=0x61; return; }
    if (prog<0x4e){ arc_4092e(r); return; }
    if (prog<0x54){ arc_4092e(r); return; }
    arc_4103a(r); W(r,0x1e)=0x09ea; B(r,0x0d)=0x71; B(r,0x38)=2;
}

void arcade_40ede(uint8_t *r){
    if (g_round==1){                                   /* 0x40EDE */
        int16_t v=(int16_t)W(r,0x34);
        if (!(v>=-384 && v<512)){ /* out of band -> fall to recheck */ }
        else { light_register_40f52(r); return; }      /* 0x40F52 */
    }
    if (arc_40e74(r)!=0){ light_register_40f52(r); return; }  /* 0x40EFA marker gone */
    /* 0x40F02 still present: off-screen boundary + animate */
    int16_t d3=(int16_t)W(r,0x16);
    if (!((uint16_t)d3<376) && !((uint16_t)d3<0xffb8)) { /* 0x40F0C off-screen: fall to frame step */ }
    if (--B(r,0x09)!=0) return;                         /* 0x40F12 frame countdown */
    B(r,0x09) = (B(r,0x2f)&1)? 3 : 2;
    if (++B(r,0x08) >= 90) B(r,0x08)=0;
    B(r,0x01) = anim_40fe0[B(r,0x08)];                  /* 0x40F3C anim frame */
}
